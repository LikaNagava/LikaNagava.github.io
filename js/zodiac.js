const sunSigns = signsInfo.map(s => new ZodiacSun(s.n, s.i, s.sd, s.m, s.d));
const moonSigns = signsInfo.map(s => new ZodiacMoon(s.n, s.i, s.md, s.m, s.d));

function renderZodiacResult(sunObj, moonObj, customName = "", time = "", isSearch = false) {
    const resultCard = document.getElementById('zodiacResult');
    if (!sunObj || !moonObj) return;

    document.getElementById('resImg').src = `../media/${sunObj.image}`;
    document.getElementById('resSign').textContent = sunObj.getSunInfo();
    document.getElementById('resDesc').textContent = moonObj.getMoonInfo();
    
    const resName = document.getElementById('resName');
    if (isSearch) {
        resName.textContent = `Информация о знаке: ${sunObj.title}`;
    } else {
        resName.textContent = customName ? `${customName}, ваш профиль:` : "Ваш профиль:";
    }

    const resTimeInfo = document.getElementById('resTimeInfo');
    if (isSearch) {
        resTimeInfo.textContent = "";
    } else {
        resTimeInfo.innerHTML = time 
            ? "✅ Расчет точный (время учтено)." 
            : "⚠️ Время не указано: Лунный знак может быть неточным.";
    }

    resultCard.style.display = 'flex';
    resultCard.scrollIntoView({ behavior: 'smooth' });
}

document.addEventListener('DOMContentLoaded', () => {
    const datalist = document.getElementById('zodiacOptions');
    sunSigns.forEach(s => {
        const opt = document.createElement('option');
        opt.value = s.title;
        datalist.appendChild(opt);
    });

    const searchInput = document.getElementById('zodiacSearch');
    const clearBtn = document.getElementById('clearSearch');

    clearBtn.addEventListener('click', () => {
        searchInput.value = "";
        searchInput.focus();
    });

    if (searchInput) {
        searchInput.addEventListener('input', (e) => {
            const val = e.target.value.trim().toLowerCase();
            const sun = sunSigns.find(s => s.title.toLowerCase() === val);
            const moon = moonSigns.find(m => m.title.toLowerCase() === val);
            
            if (sun && moon) {
                renderZodiacResult(sun, moon, "", "", true);
            }
        });
    }
});

function processZodiac() {
    const name = document.getElementById('userName').value;
    const dateVal = document.getElementById('userBirthDate').value;
    const timeVal = document.getElementById('userBirthTime').value;

    if (!dateVal) return alert("Выберите дату рождения");

    const birthDate = new Date(dateVal);
    const m = birthDate.getMonth() + 1;
    const d = birthDate.getDate();

    const sun = sunSigns.find(s => (m < s.month) || (m === s.month && d <= s.day)) || sunSigns[0];

    const refDate = new Date(Date.UTC(2024, 11, 30, 22, 27)); 
    const userDate = timeVal ? new Date(`${dateVal}T${timeVal}`) : new Date(dateVal);
    const diffDays = (userDate - refDate) / (1000 * 86400);
    const moonCycleProgress = ((diffDays % 27.32) + 27.32) % 27.32;
    const moonIndex = Math.floor(moonCycleProgress / (27.32 / 12));
    const moon = moonSigns[moonIndex % 12];

    renderZodiacResult(sun, moon, name, timeVal, false);
    closeForm();
}

function showZodiacForm() {
    document.getElementById('inputForm').style.display = 'block';
    document.getElementById('zodiacResult').style.display = 'none';
}

function closeForm() {
    document.getElementById('inputForm').style.display = 'none';
}
